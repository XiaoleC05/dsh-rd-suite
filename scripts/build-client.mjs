#!/usr/bin/env node
/**
 * Build client.js — the single browser module of this bundle.
 *
 * A DSH bundle owns exactly one client module (id = package name), so every
 * surface is composed here: each source file's factory is captured, its plugin
 * object is created, and one plugin that applies them all is registered under
 * the bundle's package name.
 *
 * The hub surface (client-sources/hub-rd.js) owns the single sidebar entry and
 * the overview page; member surfaces keep their main-area pages but drop their
 * own sidebar icons (the integrated-UI flag below).
 *
 * Sources live in client-sources/ and are the members' own client files
 * (cards.js is vendored from @deepseek-ai/dsh-client-ui-agent-preset, MIT).
 *
 * Run after changing any client source:
 *   node scripts/build-client.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const here = dirname(fileURLToPath(import.meta.url))
const root = dirname(here)
const packageName = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name

// The GitHub flow has no settings row: it is part of the mode, so its rules live
// in the Host prompt section and in the hub overview instead of a client surface.
const SOURCES = [
  'client-sources/cards.js',
  'client-sources/code-pipeline.js',
  'client-sources/memory.js',
  'client-sources/hub-rd.js',
]

/** Capture the factory function text from a module-loader client file. */
function factoryText(file) {
  const captured = []
  const window = {
    __ModuleLoader__: {
      load(definition) {
        captured.push(definition)
      },
    },
  }
  // The files only touch `window` at top level; factories run later.
  new Function('window', readFileSync(join(root, file), 'utf8'))(window)
  if (captured.length !== 1)
    throw new Error(`expected exactly one module registration in ${file}, got ${captured.length}`)
  const { id, factory } = captured[0]
  if (typeof factory !== 'function') throw new Error(`no factory in ${file} (id ${id})`)
  const text = factory.toString()
  // Method shorthand (`factory(require) {...}`) is not a standalone expression.
  return /^\s*factory\s*\(/.test(text) || /^\s*(async\s+)?factory\s*\(/.test(text)
    ? `({${text}}).factory`
    : `(${text})`
}

const parts = SOURCES.map(factoryText)
const out = [
  '/*!',
  ' * dsh-rd-suite — merged browser module (generated by scripts/build-client.mjs).',
  ' * Composes: R&D workbench hub, preset cards (vendored @deepseek-ai/dsh-client-ui-agent-preset, MIT),',
  ' * code-pipeline panel, GitHub issue-first settings row.',
  ' */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(packageName)},`,
  '  factory: require => {',
  '    const pageSources = []',
  '    const parts = []',
  '    const add = (part) => { if (part === null || part === undefined) return; parts.push(part); if (Array.isArray(part.pages)) pageSources.push(part.pages) }',
  ...parts.map((text, index) => `    add(${text}(require, pageSources)) // source ${index + 1}`),
  '    const inject = []',
  '    for (const part of parts) for (const name of part.inject ?? []) if (!inject.includes(name)) inject.push(name)',
  '    return {',
  '      inject,',
  '      apply(ctx) { for (const part of parts) part.apply(ctx) },',
  '    }',
  '  },',
  '})',
  '',
].join('\n')

const outFile = join(root, 'client.js')
writeFileSync(outFile, out, 'utf8')
execFileSync(process.execPath, ['--check', outFile], { stdio: 'pipe' })
process.stdout.write(`wrote client.js (${out.length} bytes, ${parts.length} surfaces)\n`)
